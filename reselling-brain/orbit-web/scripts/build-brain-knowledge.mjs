#!/usr/bin/env node
// Builds the Reselling Brain modules from the shared source in reselling-brain/:
//   reselling-brain/knowledge/*.md  -> functions/_lib/reselling-brain-knowledge.js
//   reselling-brain/catalog/*.json  -> functions/_lib/reselling-brain-catalog.js
// The catalogue holds LIST (selling) prices only. The build fails if a cost, margin,
// markup, wholesale, payout or commission field ever appears in it.
import {readFileSync,readdirSync,writeFileSync} from "node:fs";
import {dirname,join} from "node:path";
import {fileURLToPath} from "node:url";

const root=join(dirname(fileURLToPath(import.meta.url)),"..");
const src=join(root,"reselling-brain");
const out=join(root,"functions","_lib");

function parseDoc(file,text){
 const m=text.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
 if(!m)throw new Error(`${file}: missing front matter (--- audience: base|team|owner|sales ---)`);
 const field=k=>((m[1].match(new RegExp(`^${k}:\\s*(.+?)\\s*$`,"m"))||[])[1]||"").replace(/^"|"$/g,"");
 const audience=field("audience");
 if(!["base","team","owner","sales"].includes(audience))throw new Error(`${file}: audience must be base, team, owner or sales`);
 const id=field("id")||file.replace(/^\d+-/,"").replace(/\.md$/,"");
 return {id,audience,body:m[2].trim()};
}

const docs=readdirSync(join(src,"knowledge")).filter(f=>f.endsWith(".md")).sort()
 .map(f=>parseDoc(f,readFileSync(join(src,"knowledge",f),"utf8")));

writeFileSync(join(out,"reselling-brain-knowledge.js"),
`// GENERATED by scripts/build-brain-knowledge.mjs from reselling-brain/knowledge/ — do not edit by hand.
// Edit the knowledge files and run: node scripts/build-brain-knowledge.mjs
export const BRAIN_DOCS = Object.freeze(${JSON.stringify(docs,null,1)});
`);

const read=f=>JSON.parse(readFileSync(join(src,"catalog",f),"utf8"));
const catalog=read("catalog.json"),partners=read("partners.json"),categories=read("categories.json");

const FORBIDDEN=/^(cost|costs|cost_price|costprice|buy|buy_price|wholesale|margin|markup|payout|commission)$/i;
(function walk(node,path){
 if(Array.isArray(node))return node.forEach((v,i)=>walk(v,`${path}[${i}]`));
 if(node&&typeof node==="object")for(const [k,v] of Object.entries(node)){
  if(FORBIDDEN.test(k))throw new Error(`Catalogue must hold list prices only: forbidden field ${path}.${k}`);
  walk(v,`${path}.${k}`);
 }
})({catalog,partners,categories},"catalogue");

writeFileSync(join(out,"reselling-brain-catalog.js"),
`// GENERATED by scripts/build-brain-knowledge.mjs from reselling-brain/catalog/ — do not edit by hand.
// List (selling) prices from the Salesforce price book. No cost, markup or margin.
export const CATALOG_SOURCE = "Salesforce Standard Price Book + USD 1 – International, refreshed 14 Nov 2026";
export const CATALOG = Object.freeze(${JSON.stringify(catalog)});
export const PARTNERS = Object.freeze(${JSON.stringify(partners)});
export const CATEGORIES = Object.freeze(${JSON.stringify(categories)});
`);

console.log(`Built ${docs.length} knowledge docs and a catalogue of ${Object.keys(catalog).length} partners.`);
