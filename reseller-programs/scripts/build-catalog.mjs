#!/usr/bin/env node
/**
 * Rebuild bot/lib/catalog.data.ts from feed/*.csv
 *
 * Usage: node scripts/build-catalog.mjs
 * Then: npm run check && npx @grok/agent-sdk validate --dir .
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const feed = join(root, "feed");

function parseCsv(text) {
  const rows = [];
  let row = [];
  let cell = "";
  let inQuotes = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    const next = text[i + 1];
    if (inQuotes) {
      if (c === '"' && next === '"') {
        cell += '"';
        i++;
      } else if (c === '"') {
        inQuotes = false;
      } else {
        cell += c;
      }
      continue;
    }
    if (c === '"') {
      inQuotes = true;
      continue;
    }
    if (c === ",") {
      row.push(cell);
      cell = "";
      continue;
    }
    if (c === "\n" || (c === "\r" && next === "\n")) {
      if (c === "\r") i++;
      row.push(cell);
      if (row.some((v) => v.length)) rows.push(row);
      row = [];
      cell = "";
      continue;
    }
    if (c === "\r") {
      row.push(cell);
      if (row.some((v) => v.length)) rows.push(row);
      row = [];
      cell = "";
      continue;
    }
    cell += c;
  }
  if (cell.length || row.length) {
    row.push(cell);
    if (row.some((v) => v.length)) rows.push(row);
  }
  if (!rows.length) return [];
  const headers = rows[0].map((h) => h.trim());
  return rows.slice(1).map((r) => {
    const obj = {};
    headers.forEach((h, idx) => {
      obj[h] = (r[idx] ?? "").trim();
    });
    return obj;
  });
}

function esc(s) {
  return JSON.stringify(String(s ?? ""));
}

const partnerRows = parseCsv(readFileSync(join(feed, "partners.csv"), "utf8"));
const itemRows = parseCsv(readFileSync(join(feed, "line_items.csv"), "utf8"));
const priceRows = parseCsv(readFileSync(join(feed, "prices.csv"), "utf8"));

const partners = partnerRows.map((r) => {
  const countries = r.countries
    .split(/[|,]/)
    .map((c) => c.trim().toUpperCase())
    .filter(Boolean);
  return `  {
    id: ${esc(r.id)},
    name: ${esc(r.name)},
    countries: ${JSON.stringify(countries)},
    nature: ${esc(r.nature)},
    commercial: {
      quoteType: "Commercial" as const,
      billingModel: ${esc(r.billing_model)},
      paymentTerms: ${esc(r.payment_terms)},
      discountPolicy: ${esc(r.discount_policy)},
      notes: ${esc(r.commercial_notes)},
    },
    operational: {
      quoteType: "Operational" as const,
      fulfillment: ${esc(r.fulfillment)},
      supportModel: ${esc(r.support_model)},
      sla: ${esc(r.sla)},
      notes: ${esc(r.operational_notes)},
    },
  }`;
});

const lineItems = itemRows.map(
  (r) => `  {
    id: ${esc(r.id)},
    name: ${esc(r.name)},
    description: ${esc(r.description)},
    unit: ${esc(r.unit)},
  }`,
);

const prices = priceRows.map((r) => {
  const amount = Number(r.amount);
  if (!Number.isFinite(amount)) {
    throw new Error(`Invalid amount for ${r.line_item_id}/${r.country}: ${r.amount}`);
  }
  return `  { lineItemId: ${esc(r.line_item_id)}, country: ${esc(r.country.toUpperCase())}, currency: ${esc(r.currency)}, amount: ${amount} }`;
});

const out = `/* eslint-disable */
// AUTO-GENERATED by scripts/build-catalog.mjs — do not edit by hand.
// Edit feed/*.csv then run: npm run feed

import type { CountryPrice, LineItem, Partner } from "./catalog.js";

export const catalogSource = "feed/*.csv";
export const catalogGeneratedAt = ${esc(new Date().toISOString())};

export const partners: Partner[] = [
${partners.join(",\n")}
];

export const lineItems: LineItem[] = [
${lineItems.join(",\n")}
];

export const prices: CountryPrice[] = [
${prices.join(",\n")}
];
`;

const dest = join(root, "bot/lib/catalog.data.ts");
writeFileSync(dest, out);
console.log(
  `Wrote ${dest} (${partnerRows.length} partners, ${itemRows.length} line items, ${priceRows.length} prices)`,
);
